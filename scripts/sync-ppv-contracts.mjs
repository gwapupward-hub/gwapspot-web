#!/usr/bin/env node
/**
 * Vendors the canonical PPV reputation contracts from the PPV repository's SDK
 * (`gwapupward-hub/ppv`, `sdk/src/reputation/*.ts`) into
 * `app/lib/ppv-reputation/`. The SDK is the source of truth; this copy exists
 * so the web app can import the same pure modules under Next's bundler and
 * Node's `--experimental-strip-types` test runner, which need `.ts` specifiers.
 *
 *   PPV_SDK_DIR=../ppv/sdk node scripts/sync-ppv-contracts.mjs          # sync
 *   PPV_SDK_DIR=../ppv/sdk node scripts/sync-ppv-contracts.mjs --check  # drift check
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reputationTarget = path.join(root, "app", "lib", "ppv-reputation");
const escrowTarget = path.join(root, "app", "lib", "escrow");
const sdkDir = process.env.PPV_SDK_DIR;
const check = process.argv.includes("--check");

if (!sdkDir) {
  console.error("Set PPV_SDK_DIR to the PPV repository's sdk/ directory.");
  process.exit(2);
}

const reputationSource = path.join(sdkDir, "src", "reputation");
const escrowSource = path.join(sdkDir, "src", "escrow");
const reputationHeader = `// GENERATED by scripts/sync-ppv-contracts.mjs from gwapupward-hub/ppv sdk/src/reputation.\n// Do not edit here; change the PPV SDK and re-run the sync.\n\n`;
const escrowHeader = `// GENERATED by scripts/sync-ppv-contracts.mjs from gwapupward-hub/ppv sdk/src/escrow.\n// Do not edit here; change the PPV SDK and re-run the sync.\n\n`;

const escrowSupportFiles = ["events.ts", "receipts.ts", "reader.ts", "states.ts"];

function rewriteRelativeJsImports(source) {
  return source.replace(
    /from "((?:\.{1,2}\/)[^"]+)\.js"/g,
    'from "$1.ts"',
  );
}

async function syncFile({ sourceDir, targetDir, name, header, label }) {
  const original = await readFile(path.join(sourceDir, name), "utf8");
  const rewritten = header + rewriteRelativeJsImports(original);
  const destination = path.join(targetDir, name);
  if (check) {
    const existing = await readFile(destination, "utf8").catch(() => null);
    if (existing !== rewritten) {
      drift += 1;
      console.error(`drift: ${label}/${name}`);
    }
    return;
  }
  await writeFile(destination, rewritten);
  console.log(`synced ${label}/${name}`);
}

const reputationFiles = (await readdir(reputationSource))
  .filter((name) => name.endsWith(".ts"))
  .sort();

let drift = 0;
await mkdir(reputationTarget, { recursive: true });
await mkdir(escrowTarget, { recursive: true });

for (const name of reputationFiles) {
  await syncFile({
    sourceDir: reputationSource,
    targetDir: reputationTarget,
    name,
    header: reputationHeader,
    label: "app/lib/ppv-reputation",
  });
}

for (const name of escrowSupportFiles) {
  await syncFile({
    sourceDir: escrowSource,
    targetDir: escrowTarget,
    name,
    header: escrowHeader,
    label: "app/lib/escrow",
  });
}

if (check && drift) process.exit(1);
