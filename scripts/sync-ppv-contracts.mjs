#!/usr/bin/env node
/**
 * Vendors the canonical PPV reputation contracts from the PPV repository's SDK
 * (`gwapupward-hub/ppv`, `sdk/src/reputation/*.ts`) into
 * `app/lib/ppv-reputation/`. The SDK is the source of truth; this copy exists
 * so the web app can import the same pure modules under Next's bundler and
 * Node's `--experimental-strip-types` test runner, which need `.ts` specifiers.
 *
 *   PPV_SDK_DIR=../ppv/sdk node scripts/sync-ppv-contracts.mjs          # sync
 *   PPV_SDK_DIR=../ppv/sdk node scripts/sync-ppv-contracts.mjs --check  # drift check
 */
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "app", "lib", "ppv-reputation");
const sdkDir = process.env.PPV_SDK_DIR;
const check = process.argv.includes("--check");

if (!sdkDir) {
  console.error("Set PPV_SDK_DIR to the PPV repository's sdk/ directory.");
  process.exit(2);
}

const source = path.join(sdkDir, "src", "reputation");
const header = `// GENERATED by scripts/sync-ppv-contracts.mjs from gwapupward-hub/ppv sdk/src/reputation.\n// Do not edit here; change the PPV SDK and re-run the sync.\n\n`;

const files = (await readdir(source)).filter((name) => name.endsWith(".ts")).sort();
let drift = 0;
await mkdir(target, { recursive: true });
for (const name of files) {
  const original = await readFile(path.join(source, name), "utf8");
  const rewritten = header + original.replace(/from "(\.\/[^"]+)\.js"/g, 'from "$1.ts"');
  const destination = path.join(target, name);
  if (check) {
    const existing = await readFile(destination, "utf8").catch(() => null);
    if (existing !== rewritten) {
      drift += 1;
      console.error(`drift: app/lib/ppv-reputation/${name}`);
    }
  } else {
    await writeFile(destination, rewritten);
    console.log(`synced app/lib/ppv-reputation/${name}`);
  }
}
if (check && drift) process.exit(1);
